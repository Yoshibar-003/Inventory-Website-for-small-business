/** Returns a translate function bound to a language. */
export function makeT(lang) {
  return function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    if (vars) {
      for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
    }
    return s;
  };
}

/** Product display name in the active language, with a graceful fallback. */
export function categoryName(t, category) {
  const key = "cat." + category;
  const translated = t(key);
  return translated === key ? category : translated;
}

export function productName(product, lang) {
  if (!product) return "";
  if (lang === "th") return product.product_name_th || product.product_name;
  return product.product_name || product.product_name_th;
}
